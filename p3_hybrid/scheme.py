"""P3 — the artifact: post-quantum unlinkability with ECDSA custody.

The recipient holds a secp256k1 spending pair ``(m, M)`` and an ML-KEM viewing
pair ``(dk_view, ek_view)``::

    Sender:     (ct, S) = Encaps(ek_view)
                h, tag  = keccak256(S)
                P       = M + h*G
                announce(ct, addr(P), tag)

    Recipient:  S  = Decaps(dk_view, ct)
                h, tag = keccak256(S)
                tag must match, then addr(M + h*G) must match
                p = (m + h) mod n

Only the *unlinkability* is post-quantum; custody remains ECDSA. That is a
deliberate scope decision, not an oversight. Stealth addresses are ordinary
secp256k1 EOAs, carrying exactly the exposure every Ethereum account carries
today, whereas the announcement metadata is permanently public and can never be
re-encrypted — so harvest-now-decrypt-later applies to the linkage, and that is
what this protocol protects.

Compared with MLWE SAP (Mikić et al., JCST 2026), only the viewing key is
lattice-based and the 4416-byte Dilithium-structured spending key disappears:
1217 bytes of meta-address against 5600. Announcements are identical in size,
so P3's entire advantage lives in registration.

**The address check is mandatory.** FIPS 203 uses implicit rejection, so
``Decaps`` never fails — a foreign ciphertext returns 32 pseudorandom bytes and
therefore a well-formed-looking tag. The view tag is one byte, so roughly 1 in
256 of other people's announcements survives it, and the ``p`` derived from such
a match is a garbage key controlling nothing. Only re-deriving the address and
comparing it rejects those.
"""

from __future__ import annotations

import os
from collections.abc import Sequence
from typing import ClassVar, Final

from pqsap_core import derive, kem
from pqsap_core.derive import DeriveError
from pqsap_core.kem import SEED_BYTES, KemSpec
from pqsap_core.scheme import (
    Announcement,
    MetaAddress,
    RecipientKeys,
    ScanMatch,
    StealthScheme,
    ViewingKeys,
)

__all__ = ["P3_SCHEME_ID", "P3Hybrid"]

#: ASCII "PQ3H". ERC-5564 standardises id 1 for secp256k1 and registers nothing
#: else; this id is therefore non-standard by necessity, and the thesis
#: methodology says so explicitly.
P3_SCHEME_ID: Final[int] = 0x50513348

_SPEND_PUBKEY_BYTES: Final[int] = 33

#: R3 registers M plus a 32-byte keccak commitment to ek_view. 65 bytes total,
#: against ERC-6538's 66 — the same storage-slot count, which is the point.
_COMMITMENT_PAYLOAD_BYTES: Final[int] = _SPEND_PUBKEY_BYTES + 32

# Domain separators for deriving reproducible keys from one benchmark seed.
_KDF_SPEND: Final[bytes] = b"pqsap/p3/spend"
_KDF_KEM_0: Final[bytes] = b"pqsap/p3/kem/0"
_KDF_KEM_1: Final[bytes] = b"pqsap/p3/kem/1"


class P3Hybrid(StealthScheme):
    """ML-KEM viewing key, secp256k1 spending key.

    The ML-KEM parameter set is a constructor argument so the ML-KEM-512/768
    cost-versus-security sweep reuses this class unchanged.
    """

    scheme_id: ClassVar[int] = P3_SCHEME_ID
    name: ClassVar[str] = "p3_hybrid"

    def __init__(self, spec: KemSpec = kem.ML_KEM_768) -> None:
        self.spec = spec

    @property
    def meta_len(self) -> int:
        return _SPEND_PUBKEY_BYTES + self.spec.ek_len

    @property
    def payload_len(self) -> int:
        return self.spec.ct_len

    @property
    def param_set(self) -> str:
        return self.spec.label

    def keygen(self, seed: bytes | None = None) -> RecipientKeys:
        """Generate spending and viewing keys.

        With a seed, both keypairs are derived deterministically, so a benchmark
        sample can be regenerated byte-for-byte from the seed recorded in its
        result row.
        """
        if seed is None:
            spend_priv = self._random_scalar()
            ek_view, dk_view = kem.keygen(self.spec)
        else:
            spend_priv = self._scalar_from_seed(seed)
            kem_seed = derive.keccak256(_KDF_KEM_0 + seed) + derive.keccak256(_KDF_KEM_1 + seed)
            assert len(kem_seed) == SEED_BYTES
            ek_view, dk_view = kem.keygen(self.spec, kem_seed)

        spend_pub = derive.pubkey_from_scalar(spend_priv)
        meta = MetaAddress(self.scheme_id, spend_pub + ek_view)
        return RecipientKeys(meta=meta, spend_priv=spend_priv, view_secret=dk_view)

    def viewing_keys(self, keys: RecipientKeys) -> ViewingKeys:
        return ViewingKeys(meta=keys.meta, view_secret=keys.view_secret)

    def announce(self, meta: MetaAddress) -> Announcement:
        spend_pub, ek_view = self.split_meta(meta)
        ct, shared = kem.encaps(self.spec, ek_view)
        h, tag = derive.h_scalar_and_tag(shared)
        stealth_pub = derive.derive_stealth_pubkey(spend_pub, h)
        return Announcement(
            scheme_id=self.scheme_id,
            payload=ct,
            stealth_address=derive.eth_address(stealth_pub),
            view_tag=tag,
        )

    def scan(self, keys: ViewingKeys, announcements: Sequence[Announcement]) -> list[ScanMatch]:
        spend_pub, _ = self.split_meta(keys.meta)
        dk_view = keys.view_secret
        matches: list[ScanMatch] = []

        for index, ann in enumerate(announcements):
            if ann.scheme_id != self.scheme_id or len(ann.payload) != self.spec.ct_len:
                continue

            # Never raises: implicit rejection returns pseudorandom bytes for a
            # ciphertext that was not ours.
            shared = kem.decaps(self.spec, dk_view, ann.payload)
            try:
                h, tag = derive.h_scalar_and_tag(shared)
            except DeriveError:
                continue

            # Cheap probabilistic filter first — this is what the view tag buys.
            if tag != ann.view_tag:
                continue

            # Mandatory. Roughly 1 in 256 foreign announcements reaches here.
            stealth_pub = derive.derive_stealth_pubkey(spend_pub, h)
            if derive.eth_address(stealth_pub) != ann.stealth_address:
                continue

            matches.append(ScanMatch(index=index, stealth_address=ann.stealth_address, tweak=h))

        return matches

    def recover_spend_key(self, keys: RecipientKeys, match: ScanMatch) -> int:
        if keys.spend_priv is None:
            raise DeriveError("recipient keys carry no spending scalar")
        if match.tweak is None:
            raise DeriveError("match carries no tweak; cannot recover a spending key")
        return derive.derive_stealth_privkey(keys.spend_priv, match.tweak)

    def commitment_payload(self, meta: MetaAddress) -> bytes:
        """R3's registration payload: ``M ‖ keccak256(ek_view)``, 65 bytes.

        The encapsulation key stays off-chain; only a binding commitment to it
        is registered. 65 bytes against ERC-6538's 66 means the same number of
        storage slots, which is the parity hypothesis the thesis tests.
        """
        spend_pub, ek_view = self.split_meta(meta)
        return spend_pub + derive.keccak256(ek_view)

    def verify_commitment(self, commitment: bytes, ek_view: bytes) -> bool:
        """Check an off-chain-served ``ek_view`` against its on-chain commitment.

        A sender **must** call this before encapsulating. Without it, whoever
        serves the key can substitute their own and read every payment — the
        commitment is the only thing binding the served key to the recipient.
        """
        if len(commitment) != _COMMITMENT_PAYLOAD_BYTES:
            raise DeriveError(
                f"commitment payload must be {_COMMITMENT_PAYLOAD_BYTES} bytes, "
                f"got {len(commitment)}"
            )
        if len(ek_view) != self.spec.ek_len:
            return False
        expected = commitment[_SPEND_PUBKEY_BYTES:]
        # Not a timing-sensitive comparison: both sides are public values.
        return derive.keccak256(ek_view) == expected

    def meta_from_commitment(self, commitment: bytes, ek_view: bytes) -> MetaAddress:
        """Rebuild the full meta-address from a commitment and a served key.

        Raises:
            DeriveError: if the served key does not match the commitment, which
                means it is not the recipient's and must not be used.
        """
        if not self.verify_commitment(commitment, ek_view):
            raise DeriveError(
                "served ek_view does not match the on-chain commitment; refusing to "
                "encapsulate to a key that may not belong to the recipient"
            )
        return MetaAddress(self.scheme_id, commitment[:_SPEND_PUBKEY_BYTES] + ek_view)

    def split_meta(self, meta: MetaAddress) -> tuple[bytes, bytes]:
        """Split a registered meta-address into ``(M, ek_view)``."""
        if len(meta.payload) != self.meta_len:
            raise DeriveError(
                f"meta-address must be {self.meta_len} bytes for {self.spec.name}, "
                f"got {len(meta.payload)}"
            )
        return meta.payload[:_SPEND_PUBKEY_BYTES], meta.payload[_SPEND_PUBKEY_BYTES:]

    @staticmethod
    def _random_scalar() -> int:
        while True:
            candidate = int.from_bytes(os.urandom(32), "big") % derive.SECP256K1_N
            if candidate != 0:
                return candidate

    @staticmethod
    def _scalar_from_seed(seed: bytes) -> int:
        counter = 0
        while True:
            digest = derive.keccak256(_KDF_SPEND + seed + counter.to_bytes(4, "big"))
            candidate = int.from_bytes(digest, "big") % derive.SECP256K1_N
            if candidate != 0:
                return candidate
            counter += 1  # pragma: no cover - probability ~2^-256
